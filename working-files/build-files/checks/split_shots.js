const { chromium } = require('playwright');
(async () => {
  const [,, site, out] = process.argv;
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const phone = { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true };
  let ctx = await b.newContext({ ...phone, colorScheme: 'light' });
  let p = await ctx.newPage();
  await p.goto(`file://${site}/index.html`); await p.evaluate(() => document.fonts.ready);
  await p.screenshot({ path: out + '/home-top.png' });
  await p.evaluate(() => document.querySelector('#home-start').scrollIntoView({ behavior: 'instant' }));
  await p.waitForTimeout(300); await p.screenshot({ path: out + '/home-start.png' });
  await p.evaluate(() => document.querySelector('#home-chapters').scrollIntoView({ behavior: 'instant' }));
  await p.waitForTimeout(300); await p.screenshot({ path: out + '/home-chapters.png' });
  await ctx.close();
  ctx = await b.newContext({ ...phone, colorScheme: 'dark' });
  p = await ctx.newPage();
  await p.goto(`file://${site}/sources-and-appendix.html`); await p.evaluate(() => document.fonts.ready);
  await p.waitForTimeout(300); await p.screenshot({ path: out + '/chapter-top-dark.png' });
  await p.evaluate(() => document.querySelector('.pager').scrollIntoView({ behavior: 'instant', block: 'center' }));
  await p.waitForTimeout(300); await p.screenshot({ path: out + '/pager-dark.png' });
  await p.click('.chapters .search-open'); await p.fill('.search-q', 'strut top nuts'); await p.waitForTimeout(900);
  await p.screenshot({ path: out + '/search-dark.png' });
  await ctx.close();
  ctx = await b.newContext({ viewport: { width: 1366, height: 860 }, colorScheme: 'light' });
  p = await ctx.newPage();
  await p.goto(`file://${site}/fuel-cooling-and-ac.html#cooling-and-oil-cooler`); await p.evaluate(() => document.fonts.ready);
  await p.waitForTimeout(600); await p.screenshot({ path: out + '/desktop-chapter.png' });
  await p.goto(`file://${site}/index.html`); await p.waitForTimeout(400); await p.screenshot({ path: out + '/desktop-home.png' });
  await b.close();
})();
